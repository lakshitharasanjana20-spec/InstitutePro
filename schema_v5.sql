SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS exams (
  id INT AUTO_INCREMENT PRIMARY KEY, branch_id INT NOT NULL, batch_id INT NOT NULL,
  title VARCHAR(120) NOT NULL, exam_type ENUM('term','project','final','other') NOT NULL DEFAULT 'term',
  exam_date DATE NOT NULL, start_time TIME NULL, max_marks DECIMAL(6,2) NOT NULL DEFAULT 100,
  created_by INT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX (batch_id,exam_date), FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS exam_marks (
  id INT AUTO_INCREMENT PRIMARY KEY, exam_id INT NOT NULL, student_id INT NOT NULL,
  marks DECIMAL(6,2) NULL, absent TINYINT(1) NOT NULL DEFAULT 0, remarks VARCHAR(255),
  entered_by INT NULL, entered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY (exam_id,student_id),
  FOREIGN KEY (exam_id) REFERENCES exams(id) ON DELETE CASCADE, FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE
) ENGINE=InnoDB;
